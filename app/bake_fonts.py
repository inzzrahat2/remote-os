"""Bake TTF fonts into anti-aliased alpha bitmaps (C header) for the Remote OS UI."""
from PIL import ImageFont
F = "/usr/share/fonts/truetype/noto/NotoSans-%s.ttf"
FONTS = [  # name, file, px size, charset
    ("f_small", F % "Regular", 26, [chr(c) for c in range(32, 127)]),
    ("f_label", F % "Bold", 30, [chr(c) for c in range(32, 127)]),
    ("f_title", F % "Bold", 46, [chr(c) for c in range(32, 127)]),
    ("f_huge", F % "Bold", 150, list("0123456789-")),
]
out = ["// generated by bake_fonts.py — do not edit", "#include <stdint.h>",
       "typedef struct { int16_t w, h, xoff, yoff, adv; uint32_t off; } Glyph;",
       "typedef struct { int asc, desc, first, count; const Glyph *g; const uint8_t *bits; const char *chars; } Font;"]
for name, path, size, chars in FONTS:
    font = ImageFont.truetype(path, size)
    asc, desc = font.getmetrics()
    bits, glyphs = bytearray(), []
    for ch in chars:
        mask, (ox, oy) = font.getmask2(ch, mode="L")
        w, h = mask.size
        adv = round(font.getlength(ch))
        glyphs.append((w, h, ox, oy, adv, len(bits)))     # oy = offset from ascender line
        bits += bytes(mask)
    out.append(f"static const uint8_t {name}_bits[{len(bits)}] = {{" + ",".join(map(str, bits)) + "};")
    out.append(f"static const Glyph {name}_g[{len(glyphs)}] = {{" + ",".join("{%d,%d,%d,%d,%d,%d}" % g for g in glyphs) + "};")
    cs = "".join(chars).replace("\\", "\\\\").replace('"', '\\"')
    out.append(f'static const Font {name} = {{{asc},{desc},{ord(chars[0])},{len(chars)},{name}_g,{name}_bits,"{cs}"}};')
    print(f"{name}: {len(chars)} glyphs, {len(bits)} bytes, asc {asc}")
open("fonts.h", "w").write("\n".join(out) + "\n")
